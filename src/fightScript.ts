type Spec = [number, string, Partial<Pose>?, Ease?];
function track(base: Partial<Pose>, spec: Spec[]): Key[] {
  let cur: Pose = { ...BASE, ...base };
  const out: Key[] = [];
  let last = -1;
  for (const [t, pre, over, e] of spec) {
    if (t <= last) throw new Error(`key order ${t} <= ${last} (${pre})`);
    last = t;
    cur = { ...cur, air: 0, spin: 0, ...(PRE[pre] || {}), ...(over || {}) };
    out.push({ t, p: { ...cur }, e });
  }
  return out;
}

